@dataclass(frozen=True)
class MonthlyScenario:
    information_cutoff: str = "2026-07-16"
    horizon_months: int = 12
    paths: int = 10000
    seed: int = 2026
    fuel_shock_pct: float = 25
    demand_shock_pct: float = 0
    capacity_shock_pct: float = 0
    delivery_delay_months: int = 0
    delivery_aircraft_count: int | None = None
    delivery_group: str = "all"
    aircraft_unavailable_pct: float = 0
    availability_group: str = "all"
    regional_contract_shock_pct: float = 0
    fleet_spare_fraction: float = .02
    schedule_growth_fraction: float = 1
    regional_contract_fixed_fraction: float = .7
    geography: str = "all"
    onset_month: int = 1
    duration_months: int = 6
    recovery_half_life_months: float = 2
    response_mode: str = "assumed_constrained"
    response_lag_months: int = 1
    response_half_life_months: float = 2
    pass_through_fraction: float = .55
    demand_elasticity: float = .55
    max_yield_step_pct: float = 3
    demand_monthly_log_sd: float = .03
    fuel_demand_correlation: float = .25
    nonfuel_fixed_fraction: float = .7
    marginal_cash_tax_fraction: float = .21
    cash_floor_musd: float = 5000
    stochastic: bool = True
    cash_plan: dict | None = None
    purchase_plan: dict | None = None
    retention_plan: dict | None = None

    def validate(self) -> None:
        date.fromisoformat(self.information_cutoff)
        integers = {"horizon_months": (1, 24), "paths": (20, 50000), "seed": (0, 1_000_000_000),
                    "onset_month": (1, 24), "duration_months": (1, 24), "response_lag_months": (0, 24),
                    "delivery_delay_months": (0, 24)}
        bounds = {"fuel_shock_pct": (-60, 100), "demand_shock_pct": (-80, 100),
                  "capacity_shock_pct": (-90, 0), "recovery_half_life_months": (.1, 24),
                  "response_half_life_months": (.1, 24), "pass_through_fraction": (0, 1.25),
                  "demand_elasticity": (0, 1.5), "max_yield_step_pct": (.01, 20),
                  "demand_monthly_log_sd": (0, .3), "fuel_demand_correlation": (-.95, .95),
                  "nonfuel_fixed_fraction": (0, 1), "marginal_cash_tax_fraction": (0, .5),
                  "cash_floor_musd": (0, 100000), "aircraft_unavailable_pct": (0, 90),
                  "regional_contract_shock_pct": (-50, 100), "fleet_spare_fraction": (0, .2),
                  "schedule_growth_fraction": (0, 1), "regional_contract_fixed_fraction": (0, 1)}
        for name, (low, high) in integers.items():
            val = getattr(self, name)
            if isinstance(val, bool) or not isinstance(val, int) or not low <= val <= high:
                raise ValueError(f"{name} must be an integer between {low} and {high}")
        if self.delivery_aircraft_count is not None and (isinstance(self.delivery_aircraft_count, bool)
                or not isinstance(self.delivery_aircraft_count, int) or not 1 <= self.delivery_aircraft_count <= 1000):
            raise ValueError("delivery_aircraft_count must be null or an integer between 1 and 1000")
        for name, (low, high) in bounds.items():
            val = getattr(self, name)
            if isinstance(val, bool) or not isinstance(val, (int, float)) or not math.isfinite(val) or not low <= val <= high:
                raise ValueError(f"{name} must be between {low} and {high}")
        if self.geography not in (*MARKETS, "all"):
            raise ValueError("Unsupported geography")
        if self.delivery_group not in ("all", "narrowbody", "widebody"):
            raise ValueError("Delivery group must be all, narrowbody or widebody")
        if self.availability_group not in (*GROUPS, "all"):
            raise ValueError("Unsupported availability group")
        if self.response_mode not in {"frozen", "assumed_constrained"}:
            raise ValueError("Fitted and feasible-policy modes are not available until fitted/validated modules exist")
        if not isinstance(self.stochastic, bool):
            raise ValueError("stochastic must be a boolean")
        validate_plan(self.cash_plan, month_sequence(self.information_cutoff, self.horizon_months))
        if self.purchase_plan is not None and self.cash_plan is not None and any(e["kind"] == "repay" for e in self.cash_plan["events"]):
            raise ValueError("Purchase debt amortization and allocation of generic debt repayments are not modeled; omit repay events when using a purchase plan")


def month_sequence(cutoff: str, count: int) -> list[str]:
    d = date.fromisoformat(cutoff)
    index = d.year * 12 + d.month  # first month strictly after information cutoff's month
    return [f"{(index + i) // 12:04d}-{(index + i) % 12 + 1:02d}" for i in range(count)]


def _month_count(start: str, end: str) -> int:
    a, b = date.fromisoformat(start), date.fromisoformat(end)
    return (b.year - a.year) * 12 + b.month - a.month + 1


def baseline(snapshot: dict, cutoff: str, cash_plan: dict | None = None, purchase_plan: dict | None = None) -> dict:
    records = available_records(snapshot, cutoff)
    lookup = {(r["entity"], r["variable"]): r for r in records}

    def get(entity: str, variable: str, units: str, monthly: bool = False) -> float:
        if (entity, variable) not in lookup:
            raise ValueError(f"No verified {entity}.{variable} available at cutoff {cutoff}")
        record = lookup[entity, variable]
        if record["units"] != units:
            raise ValueError(f"Incorrect units for {entity}.{variable}")
        return record["value"] / (_month_count(record["effective_start"], record["effective_end"]) if monthly else 1)

    markets = [{"market": market,
                "asm_million": get(market, "asm", "ASM_million", True),
                "rpm_million": get(market, "rpm", "RPM_million", True),
                "passenger_revenue_musd": get(market, "passenger_revenue", "USD_million", True)} for market in MARKETS]
    for m in markets:
        if not 0 < m["rpm_million"] <= m["asm_million"] or m["passenger_revenue_musd"] <= 0:
            raise ValueError("Invalid reported market traffic/capacity/revenue")
        m["yield_usd_per_rpm"] = m["passenger_revenue_musd"] / m["rpm_million"]
    revenue = get("UAL", "operating_revenue", "USD_million", True)
    expense = get("UAL", "operating_expense", "USD_million", True)
    oi = get("UAL", "operating_income", "USD_million", True)
    fuel = get("UAL", "fuel_expense", "USD_million", True)
    gallons = get("UAL", "fuel_gallons", "gallons_million", True)
    cargo = get("UAL", "cargo_revenue", "USD_million", True)
    other = get("UAL", "other_revenue", "USD_million", True)
    if abs(sum(m["passenger_revenue_musd"] for m in markets) + cargo + other - revenue) > .01:
        raise ValueError("Market and consolidated revenues do not reconcile")
    if abs(revenue - expense - oi) > .01:
        raise ValueError("Consolidated operating identity does not reconcile")
    # SEC cash flow statements report YTD flows. Q2 is H1 minus Q1, not
    # the six-month average: Q1 advance sales can dominate the H1 run rate.
    q2_cash = {}
    cash_bridge = {}
    for variable in ("operating_cash_flow", "cash_capex"):
        h1, q1 = lookup.get(("UAL", variable)), lookup.get(("UAL", variable + "_q1"))
        if h1 is None or q1 is None:
            raise ValueError(f"No verified H1 and Q1 {variable} to derive Q2 cash flow")
        if h1["effective_start"] != q1["effective_start"] or h1["effective_end"] != "2026-06-30" or q1["effective_end"] != "2026-03-31":
            raise ValueError("Q2 cash flow derivation requires matching H1 and Q1 periods")
        if h1["units"] != "USD_million" or q1["units"] != "USD_million":
            raise ValueError("Q2 cash flow derivation requires matching USD_million units")
        q2_cash[variable] = (h1["value"] - q1["value"]) / 3
        cash_bridge[variable] = {"q2_total_musd": h1["value"] - q1["value"], "method": "H1 minus Q1",
                               "source_record_ids": [h1["record_id"], q1["record_id"]],
                               "published_on": max(h1["published_on"], q1["published_on"]),
                               "effective_start": "2026-04-01", "effective_end": "2026-06-30"}
    result = {"markets": markets, "operating_revenue_musd": revenue, "operating_expense_musd": expense,
            "operating_income_musd": oi, "fuel_expense_musd": fuel, "fuel_gallons_million": gallons,
            "nonfuel_expense_musd": expense - fuel, "cargo_revenue_musd": cargo, "other_revenue_musd": other,
            "paid_fuel_usd_per_gallon": fuel / gallons,
            "operating_cash_flow_musd": q2_cash["operating_cash_flow"],
            "cash_capex_musd": q2_cash["cash_capex"], "cash_flow_derivation": cash_bridge,
            "cash_musd": get("UAL", "cash", "USD_million"),
            "short_term_investments_musd": get("UAL", "short_term_investments", "USD_million"),
            "initial_state_effective_on": lookup["UAL", "cash"]["effective_end"],
            "regional_capacity_purchase_musd": get("UAL", "regional_capacity_purchase", "USD_million", True),
            "regional_asm_share": get("UAL", "regional_asm_share", "fraction"),
            "fleet_plan": fleet_plan(snapshot, cutoff),
            "status": "Q2 operating totals / 3; Q2 cash flows derived as H1 minus Q1, then / 3; historical cash held as opening scenario state"}
    if cash_plan is not None or purchase_plan is not None:
        result["cash_ledger"] = opening_state(snapshot, cutoff, result)
    return result


def summary(values: np.ndarray) -> dict:
    p10, p50, p90 = np.quantile(values, [.1, .5, .9])
    return {"p10": round(float(p10), 4), "p50": round(float(p50), 4), "p90": round(float(p90), 4)}


def distributions(values: np.ndarray) -> list[dict]:
    return [summary(values[:, i]) for i in range(values.shape[1])]


def _world(s: MonthlyScenario, spot: float, sigma: float,
           rng: np.random.Generator | None = None) -> tuple[np.ndarray, np.ndarray]:
    # A supplied generator advances across independent path batches. Each path
    # still starts from the same initial world state; monthly innovations remain
    # path-major, so concatenated batches reproduce one monolithic draw exactly.
    rng = np.random.default_rng(s.seed) if rng is None else rng
    z = rng.standard_normal((s.paths, s.horizon_months, 2))
    fuel_z = z[:, :, 0]
    demand_z = s.fuel_demand_correlation * fuel_z + math.sqrt(1 - s.fuel_demand_correlation ** 2) * z[:, :, 1]
    log_fuel, log_demand = np.zeros(s.paths), np.zeros(s.paths)
    fuel, demand = np.zeros((s.paths, s.horizon_months)), np.zeros((s.paths, s.horizon_months))
    for t in range(s.horizon_months):
        if s.stochastic:
            log_fuel = .75 * log_fuel + sigma * fuel_z[:, t]
            log_demand = .75 * log_demand + s.demand_monthly_log_sd * demand_z[:, t]
        fuel[:, t] = np.clip(spot * np.exp(log_fuel), .1, 20)
        demand[:, t] = np.exp(log_demand)
    return fuel, demand


def shock_weights(s: MonthlyScenario) -> np.ndarray:
    months = np.arange(1, s.horizon_months + 1)
    ending = s.onset_month + s.duration_months
    return np.where(months < s.onset_month, 0, np.where(months < ending, 1, 2. ** (-(months - ending + 1) / s.recovery_half_life_months)))


def _rollout(b: dict, s: MonthlyScenario, fuel_world: np.ndarray, demand_world: np.ndarray,
             spot: float, intervention: bool, mode: str, fleet: dict | None = None,
             recovery: np.ndarray | None = None) -> dict[str, np.ndarray]:
    asm = np.array([m["asm_million"] for m in b["markets"]])
    rpm = np.array([m["rpm_million"] for m in b["markets"]])
    yields = np.array([m["yield_usd_per_rpm"] for m in b["markets"]])
    pax = np.array([m["passenger_revenue_musd"] for m in b["markets"]])
    gallons_per_asm = b["fuel_gallons_million"] / asm.sum()
    geography = np.array([s.geography == "all" or market == s.geography for market in MARKETS], float)
    weights = shock_weights(s) if intervention else np.zeros(s.horizon_months)
    fleet = capacity_paths(b, s, b["fleet_plan"], month_sequence(s.information_cutoff, s.horizon_months), shock_weights(s)) if fleet is None else fleet
    components = fleet["intervention_components" if intervention else "control_components"]
    committed = fleet["committed_components"].sum(axis=2)
    reference_split = np.array(fleet["reference_split_asm_million"])
    cpa_base = b["regional_capacity_purchase_musd"]
    mainline_nonfuel_base = b["nonfuel_expense_musd"] - cpa_base
    if mainline_nonfuel_base < 0:
        raise ValueError("Regional contract expense exceeds consolidated nonfuel expense")
    names = ("revenue_musd", "fuel_expense_musd", "nonfuel_expense_musd", "operating_income_musd",
             "operating_cash_flow_musd", "cash_capex_musd", "free_cash_flow_musd", "cash_musd", "asm_million", "rpm_million",
             "mainline_asm_million", "regional_asm_million", "mainline_fuel_expense_musd", "regional_fuel_expense_musd",
             "regional_contract_expense_musd", "other_nonfuel_expense_musd", "unserved_schedule_asm_million")
    result = {name: np.empty((s.paths, s.horizon_months)) for name in names}
    result["market_revenue_musd"] = np.empty((s.paths, s.horizon_months, 4))
    result["market_load_factor"] = np.empty((s.paths, s.horizon_months, 4))
    result["market_yield_change_pct"] = np.empty((s.paths, s.horizon_months, 4))
    response = np.zeros((s.paths, 4))
    cash = np.full(s.paths, b["cash_musd"])
    cash_state = None
    if s.cash_plan is not None or s.purchase_plan is not None:
        cash_state = {**b["cash_ledger"]["state"], "cash_musd": cash.copy()}
        result.update({name: np.empty((s.paths, s.horizon_months)) for name in (*STOCK_OUTPUTS, *FLOW_OUTPUTS)})
        months = month_sequence(s.information_cutoff, s.horizon_months)
    purchase_cash = fleet["intervention" if intervention else "control"].get("purchase_cash")
    if purchase_cash is not None:
        result.update({name: np.empty((s.paths, s.horizon_months)) for name in (*PURCHASE_FLOWS, *PURCHASE_STOCKS)})
    fleet_track = fleet["intervention" if intervention else "control"]
    if s.retention_plan is not None:
        result.update({name: np.empty((s.paths, s.horizon_months)) for name in (*RETENTION_FLOWS, "retained_aircraft")})
    alpha = 1 - 2 ** (-1 / s.response_half_life_months)
    curve_mode = mode == RECOVERY_MODE
    if curve_mode:
        if recovery is None or recovery.shape != (s.paths, s.horizon_months):
            raise ValueError("Recovery-curve mode needs one monthly recovery curve per path")
        price_steps = np.zeros((s.paths, s.horizon_months, 4))
        prior_price = np.full((s.paths, 4), b["paid_fuel_usd_per_gallon"])
    for t in range(s.horizon_months):
        w = weights[t] * geography
        operated = components[t] * (1 + s.capacity_shock_pct / 100 * w[:, None])
        capacity = np.broadcast_to(operated.sum(axis=1), (s.paths, 4))
        delivered = np.maximum(.1, b["paid_fuel_usd_per_gallon"] + fuel_world[:, t, None] - spot + fuel_world[:, t, None] * s.fuel_shock_pct / 100 * w)
        pressure = (delivered - b["paid_fuel_usd_per_gallon"]) * asm * gallons_per_asm
        retention = fleet_track["monthly"][t].get("retention")
        extra_market_fuel = np.zeros((s.paths, 4))
        if retention is not None:
            premium = np.array([retention["fuel_burn_premium_fraction_by_group"][g] for g in GROUPS])
            extra_market_fuel = (operated[None, :, :] * gallons_per_asm * delivered[:, :, None] * premium[None, None, :]).sum(axis=2)
            pressure += extra_market_fuel
        # Normalize cost pressure by reference passenger revenue to obtain an
        # assumed yield change; this is not an estimated pricing decision rule.
        target = np.clip(s.pass_through_fraction * pressure / pax, -.5, .5)
        if mode == "assumed_constrained" and t + 1 > s.response_lag_months:
            response += np.clip(alpha * (target - response), -s.max_yield_step_pct / 100, s.max_yield_step_pct / 100)
        if curve_mode:
            # Each month's change in the delivered fuel price starts its own clock:
            # k months later, recovery[:, k] of that change, times the gallons burned
            # that month, comes back as revenue. The share is defined on revenue net
            # of any volume effect, so this mode switches off the fare-demand
            # elasticity (response is zero when demand is computed below), the
            # pass-through fraction with its lag and half-life, the +/-50% target
            # clip and the monthly yield-step cap. Fuel price falls are passed back
            # with the same curve.
            price_steps[:, t] = delivered - prior_price
            prior_price = delivered
            recovered_price = np.einsum("pk,pkm->pm", recovery[:, t::-1], price_steps[:, :t + 1])
            burn = operated * gallons_per_asm if retention is None else operated * gallons_per_asm * (1 + premium)
            recovered = recovered_price * burn.sum(axis=1)
            response = np.zeros((s.paths, 4))
        desired = rpm * (committed[t] / asm) * demand_world[:, t, None] * (1 + s.demand_shock_pct / 100 * w) * (1 + response) ** (-s.demand_elasticity)
        served = np.minimum(desired, capacity)
        if curve_mode:
            # Implied unit-revenue change that delivers the recovered dollars.
            response = np.divide(recovered, served * yields, out=np.zeros((s.paths, 4)), where=served * yields > 0)
        market_revenue = served * yields * (1 + response)
        group_fuel = (operated[None, :, :] * gallons_per_asm * delivered[:, :, None]).sum(axis=1)
        if retention is not None:
            group_fuel *= 1 + premium
        fuel_expense = group_fuel.sum(axis=1)  # Regional fuel is already in the consolidated anchor.
        capacity_ratio = capacity.sum(axis=1) / asm.sum()
        mainline_asm, regional_asm = operated[:, :2].sum(), operated[:, 2].sum()
        mainline_ratio = mainline_asm / reference_split[:, :2].sum()
        regional_ratio = regional_asm / reference_split[:, 2].sum()
        other_nonfuel = mainline_nonfuel_base * (s.nonfuel_fixed_fraction + (1 - s.nonfuel_fixed_fraction) * mainline_ratio)
        if retention is not None:
            maintenance = retention["retention_maintenance_expense_musd"]
            carrying = retention["retention_carrying_expense_musd"]
            other_nonfuel += maintenance + carrying
            result["retention_maintenance_expense_musd"][:, t] = maintenance
            result["retention_carrying_expense_musd"][:, t] = carrying
            result["retention_extra_fuel_expense_musd"][:, t] = extra_market_fuel.sum(axis=1)
            result["retained_aircraft"][:, t] = sum(retention["retained_by_group"].values())
        cpa = cpa_base * (s.regional_contract_fixed_fraction + (1 - s.regional_contract_fixed_fraction) * regional_ratio) * (1 + s.regional_contract_shock_pct / 100 * weights[t])
        nonfuel = other_nonfuel + cpa
        revenue = market_revenue.sum(axis=1) + b["cargo_revenue_musd"] * capacity_ratio + b["other_revenue_musd"]
        oi = revenue - fuel_expense - nonfuel
        # Aggregate historical OCF bridge retained as an explicit assumption. No claim
        # that advance sales, loyalty, taxes or other working capital have been fitted.
        ocf = b["operating_cash_flow_musd"] + (oi - b["operating_income_musd"]) * (1 - s.marginal_cash_tax_fraction)
        capex = np.full(s.paths, b["cash_capex_musd"])
        events = month_events(s.cash_plan, months[t], intervention) if cash_state is not None else None
        if purchase_cash is not None:
            purchase = purchase_cash["monthly"][t]
            capex = np.full(s.paths, purchase["cash_capex_musd"])
            events["borrow"] += purchase["purchase_borrowing_musd"]
            events["cash_interest"] += purchase["purchase_interest_musd"]
            events["financing_fee"] += purchase["purchase_financing_fee_musd"]
            for name in (*PURCHASE_FLOWS, *PURCHASE_STOCKS):
                result[name][:, t] = purchase[name]
        fcf = ocf - capex
        if cash_state is None:
            cash = cash + fcf
        else:
            cash_state, cash_flows = step(cash_state, events, ocf, capex)
            ocf, capex, fcf = (cash_flows[name] for name in ("operating_cash_flow_musd", "cash_capex_musd", "free_cash_flow_musd"))
            cash = cash_state["cash_musd"]
            for name in STOCK_OUTPUTS:
                result[name][:, t] = cash_state[name]
            for name in FLOW_OUTPUTS:
                result[name][:, t] = cash_flows[name]
        missed = np.maximum(0, committed[t].sum() - capacity.sum(axis=1))
        for name, value in zip(names, (revenue, fuel_expense, nonfuel, oi, ocf, capex, fcf, cash, capacity.sum(axis=1), served.sum(axis=1),
                                     mainline_asm, regional_asm, group_fuel[:, :2].sum(axis=1), group_fuel[:, 2], cpa, other_nonfuel, missed)):
            result[name][:, t] = value
        result["market_revenue_musd"][:, t] = market_revenue
        result["market_load_factor"][:, t] = np.divide(served, capacity, out=np.zeros_like(served), where=capacity > 0)
        result["market_yield_change_pct"][:, t] = response * 100
    return result


def _package(result: dict, months: list[str]) -> dict:
    flows = {name: distributions(values) for name, values in result.items() if values.ndim == 2}
    markets = {m: {name: distributions(result[name][:, :, i]) for name in ("market_revenue_musd", "market_load_factor", "market_yield_change_pct")} for i, m in enumerate(MARKETS)}
    quarters: dict[str, list[int]] = {}
    for i, month in enumerate(months):
        quarter = f"{month[:4]}-Q{(int(month[5:]) - 1) // 3 + 1}"
        quarters.setdefault(quarter, []).append(i)
    quarterly = []
    for quarter, indexes in quarters.items():
        row = {"quarter": quarter, "months_included": [months[i] for i in indexes], "complete_quarter": len(indexes) == 3}
        for name in ("revenue_musd", "operating_income_musd", "operating_cash_flow_musd", "cash_capex_musd", "free_cash_flow_musd"):
            row[name] = summary(result[name][:, indexes].sum(axis=1))
        row["ending_cash_musd"] = summary(result["cash_musd"][:, indexes[-1]])
        if "net_cash_change_musd" in result:
            for name in FLOW_OUTPUTS:
                row[name] = summary(result[name][:, indexes].sum(axis=1))
            for name in STOCK_OUTPUTS:
                row["ending_" + name] = summary(result[name][:, indexes[-1]])
        if "purchase_settlement_cash_musd" in result:
            for name in PURCHASE_FLOWS:
                row[name] = summary(result[name][:, indexes].sum(axis=1))
            for name in PURCHASE_STOCKS:
                row["ending_" + name] = summary(result[name][:, indexes[-1]])
        if "retained_aircraft" in result:
            for name in RETENTION_FLOWS:
                row[name] = summary(result[name][:, indexes].sum(axis=1))
            row["ending_retained_aircraft"] = summary(result["retained_aircraft"][:, indexes[-1]])
        quarterly.append(row)
    return {"monthly": flows, "markets": markets, "quarterly": quarterly}


def simulate_monthly(s: MonthlyScenario, snapshot: dict | None = None, fuel: list[dict] | None = None) -> dict:
    started = perf_counter()
