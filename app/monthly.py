    b = baseline(snapshot, s.information_cutoff, s.cash_plan, s.purchase_plan)
    fuel = load_fuel() if fuel is None else fuel
    fuel = [r for r in fuel if r["date"] <= s.information_cutoff]
    if len(fuel) < 30:
        raise ValueError("At least 30 fuel observations at or before the cutoff are required")
    # EIA vintage/release timestamps remain unavailable; this is labeled reconstruction.
    spot = fuel[-1]["usd_per_gallon"]
    sigma = fuel_volatility(fuel) * math.sqrt(21)
    worlds = _world(s, spot, sigma)
    months = month_sequence(s.information_cutoff, s.horizon_months)
    fleet = capacity_paths(b, s, b["fleet_plan"], months, shock_weights(s))
    control = _rollout(b, s, *worlds, spot, False, s.response_mode, fleet)
    scenario = _rollout(b, s, *worlds, spot, True, s.response_mode, fleet)
    frozen_control = _rollout(b, s, *worlds, spot, False, "frozen", fleet)
    frozen_scenario = _rollout(b, s, *worlds, spot, True, "frozen", fleet)
    impact = {name: scenario[name] - control[name] for name in control}
    frozen_impact = {name: frozen_scenario[name] - frozen_control[name] for name in control}
    manifest = {"model_version": VERSION, "scenario": asdict(s), "evidence_snapshot_id": digest(snapshot),
                "fuel_snapshot_id": digest(fuel), "fuel_last_observation": fuel[-1]["date"],
                "numpy_version": np.__version__, "information_cutoff": s.information_cutoff,
                "python_version": platform.python_version(),
                "code_sha256": hashlib.sha256(b"".join(Path(__file__).with_name(name).read_bytes() for name in ("monthly.py", "fleet.py", "evidence.py", "data.py", "cash_bridge.py"))).hexdigest()}
    manifest["run_id"] = digest(manifest)
    policy_difference = impact["free_cash_flow_musd"] - frozen_impact["free_cash_flow_musd"]
